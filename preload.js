const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  list: () => ipcRenderer.invoke('storms:list'),
  save: (id, text, mtime) => ipcRenderer.invoke('storms:save', id, text, mtime),
  saveSync: (id, text, mtime) => ipcRenderer.sendSync('storms:saveSync', id, text, mtime),
  remove: (id) => ipcRenderer.invoke('storms:remove', id),
  copy: (text) => ipcRenderer.invoke('clipboard:write', text),
  wallpaper: () => ipcRenderer.invoke('wallpaper:get'),
  chooseWallpaper: () => ipcRenderer.invoke('wallpaper:choose'),
  clearWallpaper: () => ipcRenderer.invoke('wallpaper:clear'),
  addMedia: (id, ext, bytes) => ipcRenderer.invoke('media:add', id, ext, bytes),
  readMedia: (id, name) => ipcRenderer.invoke('media:read', id, name),
  copyImage: (id, name) => ipcRenderer.invoke('media:copy', id, name),
  sweepMedia: (refs) => ipcRenderer.invoke('media:sweep', refs),
  trashMedia: (id) => ipcRenderer.invoke('media:trash', id),
  aiList: () => ipcRenderer.invoke('ai:list'),
  aiStatus: () => ipcRenderer.invoke('ai:status'),
  aiSignIn: (key, id) => ipcRenderer.invoke('ai:signin', key, id),
  aiConnect: (key, id) => ipcRenderer.invoke('ai:connect', key, id),
  aiEnable: (id, on) => ipcRenderer.invoke('ai:enable', id, on),
  aiDisconnect: (id) => ipcRenderer.invoke('ai:disconnect', id),
  aiModel: (provider, id) => ipcRenderer.invoke('ai:model', provider, id),
  aiEffort: (level) => ipcRenderer.invoke('ai:effort', level),
  aiPage: (id) => ipcRenderer.invoke('ai:page', id),
  aiEndpointModels: (key, draft) => ipcRenderer.invoke('ai:endpoint:models', key, draft),
  aiSaveEndpoint: (key, draft) => ipcRenderer.invoke('ai:endpoint:save', key, draft),
  ask: (key, request) => ipcRenderer.invoke('ai:ask', key, request),
  cancelAsk: (key) => ipcRenderer.invoke('ai:cancel', key),
  onAskText: (heard) => ipcRenderer.on('ai:text', (_e, key, text) => heard(key, text)),
  loadAsks: () => ipcRenderer.invoke('asks:load'),
  saveAsks: (id, kept) => ipcRenderer.invoke('asks:save', id, kept),
  clearAsks: () => ipcRenderer.invoke('asks:clear'),
  folder: () => ipcRenderer.invoke('folder:get'),
  chooseFolder: () => ipcRenderer.invoke('folder:choose'),
  showFolder: () => ipcRenderer.invoke('folder:show'),
  appInfo: () => ipcRenderer.invoke('app:info'),
  openPlace: (place) => ipcRenderer.invoke('app:open', place),
  openComposer: (text) => ipcRenderer.invoke('post:open', text),
  onMenu: (fn) => ipcRenderer.on('menu', (_e, action) => fn(action)),
});
